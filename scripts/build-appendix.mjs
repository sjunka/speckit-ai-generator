// Regenerates docs/REPLICATION-APPENDIX.md from the tracked source files, so
// the replication prompt can never drift from the app it describes.
//   node scripts/build-appendix.mjs   (or: npm run docs:appendix)
import { execSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

// specs/ and .specify/ hold the spec-kit artefacts that describe the app; the
// two PDF builders and the extractor are authoring tooling. None of them are
// the app, so none belong in an appendix of the app's source.
const SKIP = /^(docs\/|openspec\/|specs\/|\.specify\/|\.claude\/|\.agents\/|node_modules\/|public\/(icon|.*\.svg|favicon)|scripts\/(build-guide-pdf|build-guion-pdf|extract-from-appendix)\.mjs)|package-lock\.json|skills-lock\.json|\.mcp\.json|AGENTS\.md|CLAUDE\.md|README\.md|\.ico$|\.png$/;

const ORDER = [
  ["Configuration", /^(package\.json|next\.config\.mjs|jsconfig\.json|postcss\.config\.mjs|eslint\.config\.mjs|vitest\.config\.mjs|vitest\.setup\.js|playwright\.config\.js|doctor\.config\.json|\.react-doctor-baseline|\.env\.local\.example|\.gitignore|\.github\/)/],
  ["Design system and shell", /^(app\/globals\.css|app\/layout\.jsx|components\/ui\/|components\/Nav\.jsx)/],
  ["Routing", /^proxy\./],
  ["Library", /^lib\//],
  ["Hooks", /^hooks\//],
  ["Screens", /^app\/(page|sign-in|capture|result|dashboard|typography|globals\.test)/],
  ["API routes", /^app\/api\//],
  ["Components", /^components\//],
  ["Test infrastructure", /^(test\/|e2e\/)/],
  ["Everything else", /./],
];

const lang = (file) =>
  ({ ".jsx": "jsx", ".js": "js", ".mjs": "js", ".css": "css", ".json": "json", ".yml": "yaml" })[
    path.extname(file)
  ] ?? "text";

const files = execSync("git ls-files", { encoding: "utf8" })
  .split("\n")
  .filter((f) => f && !SKIP.test(f));

const claimed = new Set();
const sections = ORDER.map(([title, match]) => {
  const group = files.filter((f) => !claimed.has(f) && match.test(f)).sort();
  group.forEach((f) => claimed.add(f));
  return [title, group];
}).filter(([, group]) => group.length);

const body = sections
  .map(([title, group]) => {
    const blocks = group
      .map((f) => `### \`${f}\`\n\n\`\`\`${lang(f)}\n${readFileSync(f, "utf8").trimEnd()}\n\`\`\``)
      .join("\n\n");
    return `## ${title}\n\n${blocks}`;
  })
  .join("\n\n");

writeFileSync(
  "docs/REPLICATION-APPENDIX.md",
  `# Replication appendix — every file, verbatim

Generated by \`npm run docs:appendix\` from the tracked source. Do not edit by
hand; edit the source and regenerate.

This is the target state for [\`REPLICATION-PROMPT.md\`](REPLICATION-PROMPT.md).
Write the tests first and let them fail, as the prompt says — then converge on
these files. When the rebuild is done, every file below must match byte for
byte. Excluded: the docs themselves, \`openspec/\`, binary assets (\`public/icon-*.png\`,
\`app/favicon.ico\`), lockfiles, and local agent tooling.

${files.length} files.

${body}
`
);

console.log(`docs/REPLICATION-APPENDIX.md — ${files.length} files`);
